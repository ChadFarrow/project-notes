test('the dashboard caps a project at 10 branches', () => {
  const m = model();
  const p = project(m, 'fork-thing');
  p.orphanBranches = Array.from({ length: 13 }, (_, i) => ({ name: `b${i}`, committedDate: null }));
  const md = renderDashboard(m, { generatedAt: GENERATED, degradedReason: null, base: '', problems: [] });
  assert.match(md, /`b9`/);
  assert.doesNotMatch(md, /`b10`/);
  assert.match(md, /- \[3 more branches with no PR\]\(projects\/fork-thing\.md\)/);
});

