test('renderAutoBlock does not depend on the date', () => {
  const later = new Date('2027-03-01T00:00:00Z');
  for (const name of ['app-one', 'svc-core', 'fork-thing', 'secret-repo', 'hidden-repo']) {
    assert.equal(
      renderAutoBlock(project(model(later), name), model(later)),
      renderAutoBlock(project(model(), name), model()),
      name,
    );
  }
});

test('renderAutoBlock shows uses, PR states, items opened elsewhere and branches', () => {
  const block = renderAutoBlock(project(model(), 'app-one'), model());
  assert.match(block, /- \*\*Uses:\*\* \[svc-core\]\(svc-core\.md\) \(5 issues\)/);
  assert.match(block, /### Pull requests \(8\)/);
  assert.match(block, /\[#2 Draft thing\]\(\S+\) — opened 2026-08-01 · draft/);
  assert.match(block, /\[#3 Conflicted\]\(\S+\) — opened 2026-08-01 · merge conflict/);
  assert.match(block, /\[#9 Failing\]\(\S+\) — opened 2026-08-01 · checks failing/);
  assert.match(block, /\[#10 Pending\]\(\S+\) — opened 2026-08-01 · checks pending/);
  assert.match(block, /\[#11 Bot bump\]\(\S+\) — opened 2026-08-01 · by vercel/);
  assert.doesNotMatch(block, /UNKNOWN|MERGEABLE/);
  assert.match(block, /### Opened elsewhere for this project \(2\)/);
  assert.match(block, /- \[secret-repo #3 Helper for app-one\]\(https:\/\/github\.com\/ChadFarrow\/secret-repo\/pull\/3\) — PR/);
  assert.match(block, /### Branches with no open PR \(2\)/);
  assert.match(block, /- \[`newer-branch`\]\(https:\/\/github\.com\/ChadFarrow\/app-one\/tree\/newer-branch\)/);
  assert.match(block, /\\<podcast:category\\> \\\*now\\\*/);
});

test('renderAutoBlock says so when there is no open work', () => {
  assert.match(renderAutoBlock(project(model(), 'upstream-fork'), model()), /_No open work\._/);
  assert.match(renderAutoBlock(project(model(), 'upstream-fork'), model()), /fork of someone\/upstream-fork/);
  assert.match(renderAutoBlock(project(model(), 'secret-repo'), model()), /· private/);
});

test('renderAutoBlock marks an untracked project', () => {
  const block = renderAutoBlock(project(model(), 'hidden-repo'), model());
  assert.match(block, /Not tracked/);
  assert.doesNotMatch(block, /Hidden issue/);
});

// ---------- dashboard ----------

test('the dashboard has no checkboxes and every list item has a link', () => {
  const md = dashboard();
  assert.doesNotMatch(md, /- \[ \]/);
  for (const line of md.split('\n').filter((l) => l.startsWith('- '))) {
    assert.match(line, /\]\(/, line);
  }
});

test('the dashboard lists ready-but-idle PRs, longest idle first', () => {
  const md = dashboard();
  const a = md.indexOf('[#6 Unknown merge state]');
  const b = md.indexOf('[#1 Ready one]');
  assert.ok(a > 0 && b > a);
  assert.match(md, /idle 17 days · no checks/);
  assert.match(md, /idle 7 days · checks passing/);
});

