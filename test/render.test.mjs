// ---------- buildOutputs ----------

function outputs(noteTexts = NOTE_TEXTS, degradedReason = null) {
  return buildOutputs({
    owner: 'ChadFarrow',
    now: NOW,
    repos: normalizeRepos(pages),
    stars: [],
    notes: Object.entries(noteTexts).map(([file, text]) => ({ file, text })),
    auditFiles: ['2026-09-26.md', 'README.md'],
    degradedReason,
  });
}

test('buildOutputs writes every generated file', () => {
  const { files } = outputs();
  for (const f of ['LATEST.md', 'audits/2026-09-27.md', 'audits/README.md', 'INDEX.md', 'references/starred.md']) {
    assert.ok(files.has(f), f);
  }
  assert.match(files.get('audits/README.md'), /2026-09-27\.md[\s\S]*2026-09-26\.md/);
});

test('buildOutputs only adds to an existing note', () => {
  const { files } = outputs();
  const note = files.get('projects/app-one.md');
  assert.ok(note.startsWith(NOTE_TEXTS['app-one.md'].trimEnd()));
  assert.ok(note.includes(`${AUTO_START}\n<!-- Generated`));
  assert.ok(note.endsWith(`${AUTO_END}\n`));
});

test('buildOutputs creates a stub for a repo with no note', () => {
  const { files } = outputs();
  const stub = files.get('projects/secret-repo.md');
  assert.match(stub, /^# secret-repo\n/);
  assert.match(stub, /## Description\nPrivate work\n/);
  assert.match(stub, /## Live status/);
});

test('buildOutputs leaves a note with broken markers alone and reports it', () => {
  const texts = { ...NOTE_TEXTS, 'svc-core.md': `# svc-core\n${AUTO_START}\n${AUTO_START}\n` };
  const { files, problems } = outputs(texts);
  assert.equal(files.has('projects/svc-core.md'), false);
  assert.ok(problems.some((p) => p.includes('projects/svc-core.md')));
  assert.match(files.get('LATEST.md'), /## Note problems[\s\S]*projects\/svc-core\.md/);
});

test('buildOutputs is stable: a second run over its own output changes no note', () => {
  const first = outputs().files;
  const texts = {};
  for (const [path, text] of first) if (path.startsWith('projects/')) texts[path.slice('projects/'.length)] = text;
  const second = outputs(texts).files;
  for (const [path, text] of second) if (path.startsWith('projects/')) assert.equal(text, first.get(path), path);
});
