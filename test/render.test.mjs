    '## Live status',
    '',
    '- **Repo:** [ChadFarrow/svc-core](https://github.com/ChadFarrow/svc-core) · JavaScript',
    '- **Used by:** [app-one](app-one.md)',
    '',
    '### Issues (5)',
    '',
    '- [#13 Bump nostr-tools](https://github.com/ChadFarrow/svc-core/issues/13) — opened 2026-09-06',
    '- [#8 Self and unknown markers](https://github.com/ChadFarrow/svc-core/issues/8) — opened 2026-09-23',
    '- [#7 Rate limit for app-one](https://github.com/ChadFarrow/svc-core/issues/7) — opened 2026-09-24 · for [app-one](app-one.md)',
