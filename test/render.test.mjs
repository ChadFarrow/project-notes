import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { normalizeRepos, buildModel } from '../scripts/lib/model.mjs';
import { parseHeader, AUTO_START, AUTO_END } from '../scripts/lib/notes.mjs';
import {
  escapeMd, renderAutoBlock, renderDashboard, renderIndex, renderStarred,
  renderAuditsReadme, buildOutputs,
} from '../scripts/lib/render.mjs';

const pages = JSON.parse(readFileSync(new URL('./fixtures/repos-pages.json', import.meta.url)));
const NOW = new Date('2026-09-27T12:00:00Z');
const GENERATED = '2026-09-27 12:00 UTC';

const NOTE_TEXTS = {
  'app-one.md': '# app-one\n\n**Category:** Apps  \n**Uses:** svc-core  \n\n## Notes\nMine.\n',
  'svc-core.md': '# svc-core\n\n**Category:** Libraries  \n\n## Notes\n',
  'hidden-repo.md': '# hidden-repo\n\n**Track:** no  \n',
  'upstream-fork.md': '# upstream-fork\n\n**Track:** upstream  \n',
};

function model(now = NOW) {
  const notes = Object.entries(NOTE_TEXTS).map(([file, text]) => ({ file, header: parseHeader(text) }));
  return buildModel({ repos: normalizeRepos(pages), notes, now, owner: 'ChadFarrow' });
}
const project = (m, name) => m.projects.find((p) => p.name === name);
const dashboard = (opts = {}) =>
  renderDashboard(model(), { generatedAt: GENERATED, degradedReason: null, base: '', problems: [], ...opts });

// ---------- escapeMd ----------

test('escapeMd escapes markdown characters that break titles', () => {
  assert.equal(escapeMd('<podcast:category> *a* _b_ [c] `d` \\'), '\\<podcast:category\\> \\*a\\* \\_b\\_ \\[c\\] \\`d\\` \\\\');
  assert.equal(escapeMd('line\none'), 'line one');
});

// ---------- auto block ----------

